classdef MechanicalAnimation < matlab.System
    %MECHANICALANIMATION Fast-rate rotating pump/fan/flow visualization.
    %
    %   A Simulink "MATLAB System" block (interpreted, not code-generation
    %   -restricted) that draws a schematic pump and fan, each rotating at
    %   an angle integrated from the block's RPM inputs every sample —
    %   genuinely driven by simulation time and RPM, not a static image or
    %   a pre-rendered loop.
    %
    %   THIS BLOCK CONTAINS NO PHYSICS. It does not compute torque,
    %   efficiency, flow, or any diagnostic quantity — those come from
    %   DigitalTwinCoreAndDashboard.m (which itself calls the project's
    %   existing, unmodified functions). This block only rotates a
    %   picture by an angle it integrates from an RPM signal, and colors
    %   that picture from a severity signal it is given.
    %
    %   SCOPE / HONESTY NOTE (docs/INTERACTIVE_SIMULINK_DIGITAL_TWIN.md
    %   §"What is and isn't physically modeled" repeats this): the blade/
    %   impeller shapes are simple schematic line drawings, not a CAD
    %   model; "vibration" is shown only as color/label changes here, the
    %   actual vibration WAVEFORM is rendered by
    %   DigitalTwinCoreAndDashboard.m (which has the real synthesized
    %   signal, generated by generate_vibration_signal.m). The flow
    %   indicator's speed is proxied directly by the commanded RPM,
    %   citing the SAME affinity-law relationship (Q ~ N) already used in
    %   pump_model.m / fan_model.m, rather than displaying the exact
    %   simulated Q value (which is computed inside
    %   run_single_operating_point.m but is not currently one of its
    %   returned fields — adding it there was avoided specifically to
    %   keep that already-tested function unmodified).
    %
    %   Inputs (all fast-rate Simulink signals):
    %     RPM_pump, RPM_fan   - commanded shaft speeds (rpm)
    %     D_pump, D_fan       - injected severities [0,1], used only to
    %                           color the drawing (green/yellow/red)
    %     ActiveEquipmentCode - 1=Pump, 2=Fan (per interactive_code_tables.m);
    %                           the non-selected equipment is drawn dimmed
    %
    %   No outputs — this is a visualization sink.

    properties (Nontunable)
        SampleTime (1,1) double = 0.05   % 20 Hz — smooth rotation, cheap to draw
    end

    properties (Access = private)
        Figure
        AxPump
        AxFan
        AxFlow
        PumpBladeLines
        FanBladeLines
        PumpCircle
        FanCircle
        FlowDots
        ThetaPump = 0
        ThetaFan = 0
        FlowPhase = 0
    end

    methods (Access = protected)
        function setupImpl(obj)
            obj.Figure = figure('Name', 'Cooling Digital Twin — Mechanical Animation', ...
                'NumberTitle', 'off', 'Position', [80, 80, 900, 320]);

            obj.AxPump = subplot(1, 3, 1, 'Parent', obj.Figure);
            obj.AxFan  = subplot(1, 3, 2, 'Parent', obj.Figure);
            obj.AxFlow = subplot(1, 3, 3, 'Parent', obj.Figure);

            obj.PumpBladeLines = local_init_rotor(obj.AxPump, 'PUMP (impeller)');
            obj.FanBladeLines  = local_init_rotor(obj.AxFan, 'FAN (blades)');

            axis(obj.AxFlow, [0 1 0 1]); axis(obj.AxFlow, 'off');
            title(obj.AxFlow, 'Chilled water / airflow');
            obj.FlowDots = line(obj.AxFlow, nan(1,4), nan(1,4), ...
                'Marker', 'o', 'MarkerSize', 8, 'MarkerFaceColor', [0.2 0.5 0.9], ...
                'LineStyle', 'none');
        end

        function stepImpl(obj, RPM_pump, RPM_fan, D_pump, D_fan, ActiveEquipmentCode)
            if ~isvalid(obj.Figure)
                return;   % window was closed by the user; stop drawing silently
            end

            obj.ThetaPump = mod(obj.ThetaPump + RPM_pump * (2*pi/60) * obj.SampleTime, 2*pi);
            obj.ThetaFan  = mod(obj.ThetaFan  + RPM_fan  * (2*pi/60) * obj.SampleTime, 2*pi);

            pump_color = local_severity_color(D_pump);
            fan_color  = local_severity_color(D_fan);
            pump_alpha = local_active_alpha(ActiveEquipmentCode, 1);
            fan_alpha  = local_active_alpha(ActiveEquipmentCode, 2);

            local_update_rotor(obj.PumpBladeLines, obj.ThetaPump, pump_color, pump_alpha);
            local_update_rotor(obj.FanBladeLines, obj.ThetaFan, fan_color, fan_alpha);

            title(obj.AxPump, sprintf('PUMP (impeller)\n%.0f rpm', RPM_pump));
            title(obj.AxFan, sprintf('FAN (blades)\n%.0f rpm', RPM_fan));

            % Flow-speed proxy: driven by whichever equipment is active,
            % citing Q ~ N (pump_model.m / fan_model.m affinity law).
            if ActiveEquipmentCode == 1
                flow_rpm = RPM_pump;
            else
                flow_rpm = RPM_fan;
            end
            obj.FlowPhase = mod(obj.FlowPhase + (flow_rpm/1500) * obj.SampleTime, 1);
            xpos = mod(obj.FlowPhase + [0 0.25 0.5 0.75], 1);
            set(obj.FlowDots, 'XData', xpos, 'YData', 0.5*ones(size(xpos)));
        end

        function resetImpl(obj)
            obj.ThetaPump = 0;
            obj.ThetaFan = 0;
            obj.FlowPhase = 0;
        end

        function releaseImpl(obj)
            if ~isempty(obj.Figure) && isvalid(obj.Figure)
                close(obj.Figure);
            end
        end

        function st = getSampleTimeImpl(obj)
            st = createSampleTime(obj, 'Type', 'Discrete', 'SampleTime', obj.SampleTime);
        end

        function num = getNumInputsImpl(~)
            num = 5;
        end

        function num = getNumOutputsImpl(~)
            num = 0;
        end
    end
end

% ======================================================================
% Local (file-scope) helper functions
% ======================================================================
function h = local_init_rotor(ax, titleText)
%LOCAL_INIT_ROTOR Draw a circle + 4 radial "blade" lines at a fixed base
%   geometry; stepImpl only rotates/colors them (fast — no recreation).
    hold(ax, 'on');
    theta_circle = linspace(0, 2*pi, 40);
    plot(ax, cos(theta_circle), sin(theta_circle), 'k-', 'LineWidth', 1);
    h = gobjects(1, 4);
    for b = 1:4
        h(b) = line(ax, [0 1], [0 0], 'LineWidth', 3);
    end
    axis(ax, [-1.3 1.3 -1.3 1.3]); axis(ax, 'equal'); axis(ax, 'off');
    title(ax, titleText);
    hold(ax, 'off');
end

function local_update_rotor(h, theta, color, alphaVal)
%LOCAL_UPDATE_ROTOR Rotate the 4 blade lines to angle theta (+ 90 deg
%   spacing) and recolor them; alphaVal dims the non-selected equipment.
    for b = 1:4
        a = theta + (b-1)*pi/2;
        set(h(b), 'XData', [0, cos(a)], 'YData', [0, sin(a)], ...
            'Color', color * alphaVal + [1 1 1] * (1 - alphaVal));
    end
end

function color = local_severity_color(D)
%LOCAL_SEVERITY_COLOR Green (healthy) -> yellow -> red (critical), driven
%   by the injected severity D already computed upstream — not decorative.
    D = min(max(D, 0), 1);
    if D < 0.3
        color = [0.2 0.7 0.2];
    elseif D < 0.6
        color = [0.9 0.7 0.1];
    else
        color = [0.85 0.15 0.15];
    end
end

function a = local_active_alpha(activeCode, thisCode)
%LOCAL_ACTIVE_ALPHA Full color for the currently-simulated equipment,
%   dimmed for the one not selected this run.
    if activeCode == thisCode
        a = 1.0;
    else
        a = 0.25;
    end
end
